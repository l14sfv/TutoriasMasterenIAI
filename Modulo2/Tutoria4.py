# LightGBM: boosting rápido para grandes datos.

# PARA BD

# SQLAlchemy: ORM y acceso a bases de datos.
# Peewee: ORM ligero.
# psycopg: PostgreSQL.
# pymysql: MySQL.
# sqlite3: SQLite, viene con Python.

