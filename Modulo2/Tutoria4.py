#LIBRERIAS DE PYTHON

# PARA CIENCIA DE DATOS
# NumPy: cálculo numérico y arrays.
# Pandas: manipulación y análisis de tablas.
# Polars: alternativa moderna y rápida para dataframes.
# Matplotlib: gráficos base.
# Seaborn: visualización estadística.
# Plotly: gráficos interactivos.
# SciPy: ciencia numérica y métodos avanzados.
# Scikit-learn: machine learning clásico.
# Statsmodels: modelos estadísticos.

# PARA IA

# TensorFlow: deep learning.
# PyTorch: deep learning e investigación.
# Keras: API de alto nivel para redes neuronales.
